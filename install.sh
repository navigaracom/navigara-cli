#!/bin/sh
#
# Navigara CLI installer
#
# This script downloads ONE pinned release of the `navigara` binary from GitHub
# Releases, checks its SHA-256 digest against the value written below, and only
# then installs it. Nothing downloaded runs before the digest matches.
#
#   curl -fsSL https://navigara.com/cli | sh                   # into ~/.local/bin, then navigara wizard
#   curl -fsSL https://navigara.com/cli | sh -s -- --prefix DIR
#   sh install.sh --system        # into /opt/navigara/bin; run as root (MDM), no wizard
#   sh install.sh --no-wizard     # install only
#   sh install.sh --help
#
# Everything runs from main at the last line, so a truncated download runs nothing.
#
# Enterprises: download this file from the GitHub release, review it, and host it
# yourselves or embed it in your MDM policy. Only the release block below changes
# between releases, so an upgrade review is a short diff.
#
# Exit codes: 0 installed, 1 verification or installation failure, 2 invalid usage.

# ---- release block: regenerated by the release workflow, review on upgrade ----
VERSION="1.0.0"
SHA256_DARWIN_ARM64=""
SHA256_DARWIN_AMD64=""
SHA256_LINUX_ARM64=""
SHA256_LINUX_AMD64=""
# ---- end release block --------------------------------------------------------

set -eu

REPO="navigaracom/navigara-cli"
BASE_URL="https://github.com/${REPO}/releases/download/v${VERSION}"
USER_PREFIX="${HOME:-}/.local/bin"
SYSTEM_PREFIX="/opt/navigara/bin"

die() {
  printf 'install.sh: %s\n' "$*" >&2
  exit 1
}

usage() {
  cat <<EOF
Usage: sh install.sh [--prefix DIR | --system] [--no-wizard] [--help]

Installs navigara ${VERSION} from
  ${BASE_URL}
after verifying the SHA-256 digest embedded in this script,
then runs navigara wizard when a terminal is available.

  --prefix DIR  install into DIR (default: ${USER_PREFIX})
  --system      install into ${SYSTEM_PREFIX}; must run as root; no wizard
  --no-wizard   do not run navigara wizard after the install
  -h, --help    show this help
EOF
}

usage_error() {
  printf 'install.sh: %s\n' "$*" >&2
  usage >&2
  exit 2
}

platform() {
  os="$(uname -s)"
  arch="$(uname -m)"
  case "$os" in
    Darwin) os="darwin" ;;
    Linux) os="linux" ;;
    *) die "unsupported operating system: $os" ;;
  esac
  case "$arch" in
    arm64 | aarch64) arch="arm64" ;;
    x86_64 | amd64) arch="amd64" ;;
    *) die "unsupported architecture: $arch" ;;
  esac
  printf '%s-%s' "$os" "$arch"
}

pinned_digest() {
  case "$1" in
    darwin-arm64) printf '%s' "$SHA256_DARWIN_ARM64" ;;
    darwin-amd64) printf '%s' "$SHA256_DARWIN_AMD64" ;;
    linux-arm64) printf '%s' "$SHA256_LINUX_ARM64" ;;
    linux-amd64) printf '%s' "$SHA256_LINUX_AMD64" ;;
    *) printf '' ;;
  esac
}

sha256_of() {
  if command -v sha256sum >/dev/null 2>&1; then
    sha256sum "$1" | awk '{print $1}'
  elif command -v shasum >/dev/null 2>&1; then
    shasum -a 256 "$1" | awk '{print $1}'
  else
    die "need sha256sum or shasum to verify the download"
  fi
}

fetch() {
  # HTTPS only, including redirects; GitHub redirects release assets to its CDN.
  if command -v curl >/dev/null 2>&1; then
    curl --fail --silent --show-error --location --proto '=https' --proto-redir '=https' \
      --tlsv1.2 --retry 3 --output "$2" "$1"
  elif command -v wget >/dev/null 2>&1; then
    wget --quiet --https-only --output-document="$2" "$1"
  else
    die "need curl or wget to download the release"
  fi
}

add_to_path() {
  case "${SHELL:-}" in
    */zsh) rc="${HOME}/.zshrc" ;;
    */bash) [ "$(uname -s)" = "Darwin" ] && rc="${HOME}/.bash_profile" || rc="${HOME}/.bashrc" ;;
    *)
      printf 'Add %s to your PATH to run navigara by name.\n' "$1"
      return
      ;;
  esac
  line="export PATH=\"$1:\$PATH\""
  if ! grep -qsxF "$line" "$rc"; then
    printf '\n# Added by the Navigara CLI installer\n%s\n' "$line" >>"$rc"
    printf 'Added %s to your PATH in %s\n' "$1" "$rc"
  fi
  printf 'Open a new terminal to run navigara by name.\n'
}

main() {
  prefix="$USER_PREFIX" system="no" wizard="yes"
  while [ $# -gt 0 ]; do
    case "$1" in
      --prefix)
        [ $# -ge 2 ] || usage_error "--prefix needs a directory"
        prefix="$2"
        shift 2
        ;;
      --prefix=*)
        prefix="${1#--prefix=}"
        shift
        ;;
      --system)
        system="yes"
        prefix="$SYSTEM_PREFIX"
        shift
        ;;
      --no-wizard)
        wizard="no"
        shift
        ;;
      -h | --help)
        usage
        exit 0
        ;;
      *) usage_error "unknown argument: $1" ;;
    esac
  done
  [ -n "$prefix" ] || usage_error "--prefix must not be empty"
  if [ "$system" = "no" ] && [ "$prefix" = "$USER_PREFIX" ] && [ -z "${HOME:-}" ]; then
    die "HOME is not set; pass --prefix DIR or --system"
  fi

  if [ "$(id -u)" -eq 0 ] && [ "$system" = "no" ]; then
    die "running as root; use --system for a machine-wide install, or run as the user"
  fi
  if [ "$system" = "yes" ] && [ "$(id -u)" -ne 0 ]; then
    die "--system must run as root"
  fi

  target="$(platform)"
  expected="$(pinned_digest "$target")"
  case "$expected" in
    '' | *[!0-9a-f]*)
      die "no pinned SHA-256 digest for ${target} in this copy of install.sh; refusing to install"
      ;;
  esac
  [ "${#expected}" -eq 64 ] || die "pinned digest for ${target} is not 64 hex characters; refusing to install"

  staged=""
  asset="navigara-${VERSION}-${target}"
  url="${BASE_URL}/${asset}"
  umask 022
  tmpdir="$(mktemp -d)"
  # shellcheck disable=SC2064 # expand tmpdir now; staged is read at exit on purpose
  trap "rm -rf '${tmpdir}' \${staged:+\"\$staged\"}" EXIT
  file="${tmpdir}/${asset}"

  printf 'Downloading %s\n' "$url"
  fetch "$url" "$file" || die "download failed; nothing was installed"

  actual="$(sha256_of "$file")"
  if [ "$actual" != "$expected" ]; then
    die "SHA-256 mismatch for ${asset}
  expected ${expected}
  actual   ${actual}
The download was discarded. Nothing was installed."
  fi
  printf 'Verified SHA-256 %s\n' "$actual"

  chmod 0755 "$file"
  mkdir -p "$prefix"
  dest="${prefix}/navigara"
  staged="${prefix}/.navigara.${VERSION}.$$"
  cp "$file" "$staged"
  chmod 0755 "$staged"
  mv -f "$staged" "$dest"
  staged=""
  printf 'Installed %s\n' "$dest"

  if [ "$system" = "no" ]; then
    "$dest" --version || die "installed binary did not start"
    case ":${PATH}:" in
      *":${prefix}:"*) ;;
      *) add_to_path "$prefix" ;;
    esac
    # Under curl | sh, stdin is the script itself; the wizard reads the terminal.
    if [ "$wizard" = "yes" ] && (: </dev/tty) 2>/dev/null; then
      "$dest" wizard </dev/tty
    fi
  fi
}

main "$@"

# Navigara CLI installer for Windows
#
# This script downloads ONE pinned release of navigara.exe from GitHub Releases,
# checks its SHA-256 digest against the value written below, and only then
# installs it. Nothing downloaded runs before the digest matches.
#
#   irm https://github.com/navigaracom/navigara-cli/releases/latest/download/install.ps1 | iex  # install, then navigara wizard
#   & ([scriptblock]::Create((irm https://github.com/navigaracom/navigara-cli/releases/latest/download/install.ps1))) -NoWizard
#   powershell -ExecutionPolicy Bypass -File install.ps1 -Prefix DIR
#   powershell -ExecutionPolicy Bypass -File install.ps1 -LocalFile navigara.exe
#
# -LocalFile installs an .exe that you built or downloaded yourself, for example
# a CI artifact. It skips the pinned digest, because you vouch for that file.
#
# MDM (Intune): run as the signed-in user, with an Analytics Ingestor key in
# NAVIGARA_TOKEN. Instead of the wizard, the script configures telemetry and
# uploads history for that user, like navigara mdm does on macOS and Linux:
#
#   $env:NAVIGARA_TOKEN = '<key>'
#   & ([scriptblock]::Create((irm https://github.com/navigaracom/navigara-cli/releases/latest/download/install.ps1))) -NavigaraHost https://app.navigara.com
#
# Exit codes: 0 installed, 1 verification, installation or setup failure,
# 3 no signed-in Claude Code or Codex account yet (MDM; run again later).

param(
    [string]$Prefix = (Join-Path $env:LOCALAPPDATA 'Programs\navigara'),
    [string]$LocalFile = '',
    [switch]$NoWizard,
    [string]$NavigaraHost = 'https://app.navigara.com',
    [ValidateSet('all', 'claude', 'codex')][string]$Source = 'all',
    [switch]$Help
)

# ---- release block: regenerated by the release workflow, review on upgrade ----
$VERSION = '1.0.0'
$SHA256_WINDOWS_ARM64 = ''
$SHA256_WINDOWS_AMD64 = ''
# ---- end release block --------------------------------------------------------

$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'

# throw, not exit: under irm | iex, exit would close the user's terminal.
function Fail([string]$Message) {
    throw "install.ps1: $Message"
}

function Add-UserPath([string]$Dir) {
    # Read the raw value, so that %VARIABLES% in the user PATH stay unexpanded.
    $key = Get-Item 'HKCU:\Environment'
    $path = $key.GetValue('Path', '', 'DoNotExpandEnvironmentNames')
    if (-not (($env:Path -split ';') -contains $Dir)) { $env:Path = "$env:Path;$Dir" }
    if (($path -split ';') -contains $Dir) { return }
    $path = (@($path -split ';' | Where-Object { $_ }) + $Dir) -join ';'
    Set-ItemProperty -Path 'HKCU:\Environment' -Name 'Path' -Value $path -Type ExpandString
    # Deleting a user variable makes .NET tell running programs that the environment changed.
    [Environment]::SetEnvironmentVariable('NAVIGARA_INSTALL_NOTIFY', $null, 'User')
    Write-Output "Added $Dir to your user PATH. Open a new terminal to run navigara by name."
}

function Install-Navigara {
    if ($Help) {
        Write-Output "Usage: install.ps1 [-Prefix DIR] [-LocalFile FILE] [-NoWizard] [-NavigaraHost ORIGIN] [-Source SOURCE] [-Help]

Installs navigara $VERSION from https://github.com/navigaracom/navigara-cli/releases
after verifying the SHA-256 digest embedded in this script,
then runs navigara wizard.

  -Prefix DIR      install into DIR (default: $Prefix)
  -LocalFile FILE  install FILE instead of the download; no digest check
  -NoWizard        do not run navigara wizard after the install
  -NavigaraHost    Navigara origin for MDM (default: https://app.navigara.com)
  -Source          tools to configure for MDM: all, claude, codex (default: all)
  -Help            show this help

With NAVIGARA_TOKEN set (MDM), it configures telemetry and uploads history
for the signed-in user instead of running the wizard."
        return
    }
    if (-not $Prefix) { Fail '-Prefix must not be empty' }
    $Prefix = $ExecutionContext.SessionState.Path.GetUnresolvedProviderPathFromPSPath($Prefix)
    $NavigaraHost = $NavigaraHost.TrimEnd('/')

    $tmp = Join-Path ([IO.Path]::GetTempPath()) ("navigara-" + [Guid]::NewGuid())
    New-Item -ItemType Directory -Path $tmp | Out-Null
    try {
        if ($LocalFile) {
            $file = (Resolve-Path -LiteralPath $LocalFile).Path
            Write-Output "Installing local file $file (SHA-256 $((Get-FileHash -Algorithm SHA256 -LiteralPath $file).Hash.ToLower()))"
        } else {
            $arch = [Runtime.InteropServices.RuntimeInformation]::OSArchitecture.ToString()
            switch ($arch) {
                'X64' { $target = 'windows-amd64'; $expected = $SHA256_WINDOWS_AMD64 }
                'Arm64' { $target = 'windows-arm64'; $expected = $SHA256_WINDOWS_ARM64 }
                default { Fail "unsupported architecture: $arch" }
            }
            if ($expected -notmatch '^[0-9a-f]{64}$') {
                Fail "no pinned SHA-256 digest for $target in this copy of install.ps1; refusing to install"
            }
            $asset = "navigara-$VERSION-$target.exe"
            $url = "https://github.com/navigaracom/navigara-cli/releases/download/v$VERSION/$asset"
            $file = Join-Path $tmp $asset
            [Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12
            Write-Output "Downloading $url"
            try {
                Invoke-WebRequest -UseBasicParsing -Uri $url -OutFile $file
            } catch {
                Fail "download failed; nothing was installed: $_"
            }
            $actual = (Get-FileHash -Algorithm SHA256 -LiteralPath $file).Hash.ToLower()
            if ($actual -ne $expected) {
                Fail "SHA-256 mismatch for $asset
  expected $expected
  actual   $actual
The download was discarded. Nothing was installed."
            }
            Write-Output "Verified SHA-256 $actual"
        }

        New-Item -ItemType Directory -Force -Path $Prefix | Out-Null
        $dest = Join-Path $Prefix 'navigara.exe'
        $staged = Join-Path $Prefix ".navigara.$VERSION.$PID.exe"
        Copy-Item -LiteralPath $file -Destination $staged
        try {
            Move-Item -LiteralPath $staged -Destination $dest -Force
        } catch {
            Remove-Item -LiteralPath $staged -Force -ErrorAction SilentlyContinue
            Fail "could not replace $dest; close every running navigara and try again: $_"
        }
        Write-Output "Installed $dest"
    } finally {
        Remove-Item -LiteralPath $tmp -Recurse -Force -ErrorAction SilentlyContinue
    }

    & $dest --version
    if ($LASTEXITCODE -ne 0) { Fail 'installed binary did not start' }
    Add-UserPath $Prefix
    if ($env:NAVIGARA_TOKEN) {
        & $dest sessions config patch --host $NavigaraHost --apply --source $Source
        if ($LASTEXITCODE -eq 3) {
            Write-Output 'Skipped: no signed-in Claude Code or Codex account yet; run this script again later.'
            $script:ExitCode = 3
            return
        }
        if ($LASTEXITCODE -ne 0) { Fail 'sessions config patch failed' }
        & $dest sessions upload --url "$NavigaraHost/api" --source $Source
        if ($LASTEXITCODE -ne 0) { Fail 'sessions upload failed' }
    } elseif (-not $NoWizard) {
        & $dest wizard
        if ($LASTEXITCODE -ne 0) { Fail "navigara wizard failed; run navigara wizard again" }
    }
}

$script:ExitCode = 0
Install-Navigara
# Only MDM runs (NAVIGARA_TOKEN set) set a code; exit tells Intune to retry.
if ($script:ExitCode -ne 0) { exit $script:ExitCode }
